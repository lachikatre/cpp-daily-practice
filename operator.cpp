#include<iostream>
using namespace std;
int main(){
 int a=2;
 int b=3;
 //Arithmetic operators 
 cout<<"a+b="<<(a+b)<<endl;
cout<<"a-b="<<(a-b)<<endl;
cout<<"a/b="<<(a/b)<<endl;
cout<<"a*b="<<(a*b)<<endl;
cout<<"a%b="<<(a%b)<<endl;
cout<<"a++="<<(a++)<<endl;
 //Relational operators 
cout<<"a==b="<<(a==b)<<endl;
cout<<"a!=b="<<(a!=b)<<endl;
cout<<"a>b="<<(a>b)<<endl;
cout<<"a<b="<<(a<b)<<endl;
cout<<"a<=b="<<(a<=b)<<endl;
cout<<"a>=b="<<(a>=b)<<endl;
//logical operator 
cout<<"((a==b)&&(a<b))="<<((a==b)&&(a<b))<<endl;
cout<<"((a==b)||(a<b))="<<((a==b)||(a<b))<<endl;
cout<<"!((a==b)&&(a<b))="<<!((a==b)&&(a<b))<<endl;
return 0;
}

